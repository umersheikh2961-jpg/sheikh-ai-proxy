      const digits=text.replace(/\D/g,'');
      if(digits.length<7){ await botMsg("That doesn't look like a valid phone number — try again?"); return; }
      lead.phone=text.trim(); leadStep='email';
      await botMsg("Got it! And your email?");
      document.getElementById('rrxInp').placeholder="e.g. john@example.com";
