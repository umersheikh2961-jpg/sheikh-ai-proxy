  async function getAI(userText){
    history.push({role:'user',content:userText});
    if(!CFG.apiEndpoint){
      return "Thanks for your message! For immediate help, tap WhatsApp Us below.";
    }
    try{
      const res=await fetch(CFG.apiEndpoint,{
        method:'POST', headers:{'Content-Type':'application/json'},
        body:JSON.stringify({message:userText,conversationHistory:history})
      });
      const data=await res.json();
      const reply=data.response||"I'd love to help! Could you share a bit more detail?";
      history.push({role:'assistant',content:reply});
      return reply;
    }catch(err){
      console.error('RoofRex widget API error:', err);
      return "Thanks for your message! For immediate help, tap WhatsApp Us below.";
    }
  }

